    async def _setoneword_cmd(self, event):
        try:
            arg = event.pattern_match.group(1) if event.pattern_match else ""
            words = None
            if arg:
                words = arg.strip().split()
            elif event.is_reply:
                replied = await event.get_reply_message()
                if replied:
                    content = None
                    if replied.text:
                        content = replied.text
                    elif replied.document:
                        mime = replied.document.mime_type
                        is_text = False
                        if mime and mime.startswith("text/"):
                            is_text = True
                        elif replied.document.attributes:
                            for attr in replied.document.attributes:
                                if hasattr(attr, 'file_name') and attr.file_name and attr.file_name.lower().endswith('.txt'):
                                    is_text = True
                                    break
                        if is_text:
                            try:
                                with tempfile.NamedTemporaryFile(delete=False, suffix=".txt") as tmp:
                                    tmp_path = tmp.name
                                await self.client.download_media(replied, file=tmp_path)
                                with open(tmp_path, "r", encoding="utf-8") as f:
                                    content = f.read()
                                os.unlink(tmp_path)
                            except Exception as e:
                                await self.edit_quote(event, f"⚠ Could not read file: {e}")
                                return
                        else:
                            await self.edit_quote(event, "⚠ Reply with a text message or .txt file.")
                            return
                    if content:
                        words = content.strip().split()
                    else:
                        await self.edit_quote(event, "⚠ No text found.")
                        return
                else:
                    await self.edit_quote(event, "⚠ No message replied.")
                    return
            if not words:
                await self.edit_quote(event, "⚠ No words provided.")
                return
            self.oneword_default = words
            self._save_settings()
            await self.edit_quote(event, f"✅ Default oneword list set ({len(words)} words).")
        except Exception as e:
            logger.error(f".setoneword error for user {self.user_id}: {e}", exc_info=True)

