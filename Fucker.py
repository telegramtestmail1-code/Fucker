# -------- Blocklist helpers --------
def block_user(user_id: int, reason: str = ""):
    with get_db() as conn:
        conn.execute(
            "INSERT OR REPLACE INTO blocked_users (user_id, reason) VALUES (?, ?)",
            (user_id, reason or "")
        )
        conn.commit()

def unblock_user(user_id: int):
    with get_db() as conn:
        conn.execute("DELETE FROM blocked_users WHERE user_id = ?", (user_id,))
        conn.commit()

def is_user_blocked(user_id: int) -> bool:
    with get_db() as conn:
        row = conn.execute("SELECT user_id FROM blocked_users WHERE user_id = ?", (user_id,)).fetchone()
        return row is not None

def get_block_reason(user_id: int) -> str:
    with get_db() as conn:
        row = conn.execute("SELECT reason FROM blocked_users WHERE user_id = ?", (user_id,)).fetchone()
        return row["reason"] if row else ""

def get_all_blocked_users() -> list:
    with get_db() as conn:
        rows = conn.execute("SELECT user_id, reason, blocked_at FROM blocked_users ORDER BY blocked_at DESC").fetchall()
        return [dict(r) for r in rows]

