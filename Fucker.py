    def _cancel_task(self, key: str):
        task = self.loop_tasks.get(key)
        if task and not task.done():
            try:
                task.cancel()
            except Exception:
                pass
        self.loop_tasks.pop(key, None)

    async def _spam_cmd(self, event):
        try:
            arg = event.pattern_match.group(1) if event.pattern_match else ""
            if not arg:
                await self.edit_quote(event, "❌ Usage: `.spam <count> <text>`")
                return
            parts = arg.split(maxsplit=1)
            if len(parts) < 2:
                await self.edit_quote(event, "❌ Usage: `.spam <count> <text>`")
                return
            try:
                count = int(parts[0])
            except Exception:
                await self.edit_quote(event, "❌ Count must be a number.")
                return
            if count < 1 or count > 500:
                await self.edit_quote(event, "❌ Count must be between 1 and 500.")
                return
            text = parts[1].strip()
            if not text:
                await self.edit_quote(event, "❌ Message text is empty.")
                return
            chat_id = event.chat_id
            reply_to = None
            if event.is_reply:
                try:
                    replied = await event.get_reply_message()
                    if replied:
                        reply_to = replied.id
                except Exception:
                    pass
            await event.delete()
            self._cancel_task("spam")
            task = asyncio.create_task(self._run_spam(count, chat_id, text, reply_to, "spam"))
            self.loop_tasks["spam"] = task
        except Exception as e:
            logger.error(f".spam error for user {self.user_id}: {e}", exc_info=True)
            await self.edit_quote(event, "⚠ Error starting spam.")

    async def _run_spam(self, count, chat_id, text, reply_to, key):
        try:
            for _ in range(count):
                try:
                    await self.client.send_message(chat_id, text, reply_to=reply_to)
                except FloodWaitError as e:
                    await asyncio.sleep(e.seconds + 1)
                except Exception as e:
                    logger.warning(f"spam send error: {e}")
                try:
                    await asyncio.sleep(self.loop_delay)
                except asyncio.CancelledError:
                    raise
        except asyncio.CancelledError:
            pass
        finally:
            self.loop_tasks.pop(key, None)

    async def _stopspam_cmd(self, event):
        try:
            had = "spam" in self.loop_tasks
            self._cancel_task("spam")
            await self.edit_quote(event, "✅ Spam stopped." if had else "ℹ No spam loop running.")
        except Exception as e:
            logger.error(f".stopspam error: {e}", exc_info=True)

